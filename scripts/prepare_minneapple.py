#!/usr/bin/env python3
"""Convert MinneApple detection data to the ATOH YOLO staging format.

The script is read-only by default. Pass --execute to write the converted
images and labels. It reads the compressed archives directly; extracting the
source archives first is not required.
"""

from __future__ import annotations

import argparse
import json
import sys
import tarfile
import zipfile
from collections import defaultdict
from io import BytesIO
from pathlib import Path, PurePosixPath
from typing import Any

import numpy as np
from PIL import Image, UnidentifiedImageError


APPLE_CLASS_ID = 0
IMAGE_SUFFIXES = {".jpg", ".jpeg", ".png"}
TRAIN_IMAGE_PREFIX = "detection/train/images/"
TRAIN_MASK_PREFIX = "detection/train/masks/"
TEST_IMAGE_PREFIX = "detection/test/images/"
TEST_GROUND_TRUTH = "test_data/detection/ground_truth.json"
TEST_MAPPING = "test_data/detection/mapping.json"


def parse_args() -> argparse.Namespace:
    home = Path.home()
    parser = argparse.ArgumentParser(
        description=(
            "Convert MinneApple train instance masks and COCO test boxes "
            "to normalized YOLO detection labels."
        )
    )
    parser.add_argument(
        "--train-archive",
        type=Path,
        default=home / "Downloads" / "mineapple.gz",
        help="MinneApple tar.gz archive containing detection/train and detection/test.",
    )
    parser.add_argument(
        "--test-archive",
        type=Path,
        default=home / "Downloads" / "mineapple1.zip",
        help="MinneApple zip archive containing test_data/detection JSON files.",
    )
    parser.add_argument(
        "--output",
        type=Path,
        default=(
            home
            / "projects"
            / "atoh_agriculture"
            / "datasets"
            / "staging"
            / "minneapple"
        ),
        help="Output staging directory.",
    )
    parser.add_argument(
        "--min-instance-pixels",
        type=int,
        default=1,
        help="Ignore mask instances with fewer pixels than this value (default: 1).",
    )
    parser.add_argument(
        "--execute",
        action="store_true",
        help="Write output files. Without this flag the script performs a dry run.",
    )
    parser.add_argument(
        "--overwrite",
        action="store_true",
        help="Allow replacement of files previously generated by this script.",
    )
    return parser.parse_args()


def read_json_from_zip(archive: zipfile.ZipFile, member: str) -> Any:
    try:
        return json.loads(archive.read(member))
    except KeyError as error:
        raise RuntimeError(f"Required file is missing from zip: {member}") from error


def image_filename(info: dict[str, Any]) -> str:
    filename = info.get("filename", info.get("file_name"))
    if not filename:
        raise RuntimeError(f"COCO image entry has no filename: {info}")
    return PurePosixPath(str(filename)).name


def coco_bbox_to_yolo(
    bbox: list[float], width: int, height: int
) -> tuple[str | None, bool]:
    """Return a YOLO label line and whether the COCO box needed clipping."""
    if len(bbox) != 4 or width <= 0 or height <= 0:
        return None, False

    x, y, box_width, box_height = map(float, bbox)
    x1 = max(0.0, min(float(width), x))
    y1 = max(0.0, min(float(height), y))
    x2 = max(0.0, min(float(width), x + box_width))
    y2 = max(0.0, min(float(height), y + box_height))
    clipped = (x1, y1, x2, y2) != (x, y, x + box_width, y + box_height)

    if x2 <= x1 or y2 <= y1:
        return None, clipped

    center_x = ((x1 + x2) / 2.0) / width
    center_y = ((y1 + y2) / 2.0) / height
    normalized_width = (x2 - x1) / width
    normalized_height = (y2 - y1) / height
    line = (
        f"{APPLE_CLASS_ID} {center_x:.8f} {center_y:.8f} "
        f"{normalized_width:.8f} {normalized_height:.8f}"
    )
    return line, clipped


def load_test_labels(
    test_archive: Path,
) -> tuple[dict[str, list[str]], dict[str, tuple[int, int]], dict[str, int]]:
    labels: dict[str, list[str]] = defaultdict(list)
    dimensions: dict[str, tuple[int, int]] = {}
    stats = {
        "coco_images": 0,
        "mapping_entries": 0,
        "coco_annotations": 0,
        "valid_test_boxes": 0,
        "invalid_test_boxes": 0,
        "clipped_test_boxes": 0,
        "annotations_without_image": 0,
        "mapping_mismatches": 0,
    }

    with zipfile.ZipFile(test_archive) as archive:
        ground_truth = read_json_from_zip(archive, TEST_GROUND_TRUTH)
        mapping = read_json_from_zip(archive, TEST_MAPPING)

    if not isinstance(ground_truth, dict):
        raise RuntimeError("Detection ground_truth.json is not a COCO dictionary.")
    if not isinstance(mapping, dict):
        raise RuntimeError("Detection mapping.json is not a dictionary.")

    images = ground_truth.get("images", [])
    annotations = ground_truth.get("annotations", [])
    if not isinstance(images, list) or not isinstance(annotations, list):
        raise RuntimeError("COCO images or annotations is not a list.")

    id_to_filename: dict[int, str] = {}
    for info in images:
        image_id = int(info["id"])
        filename = image_filename(info)
        width = int(info["width"])
        height = int(info["height"])
        id_to_filename[image_id] = filename
        dimensions[filename] = (width, height)
        labels.setdefault(filename, [])

    stats["coco_images"] = len(images)
    stats["mapping_entries"] = len(mapping)

    for filename, raw_image_id in mapping.items():
        clean_filename = PurePosixPath(str(filename)).name
        image_id = int(raw_image_id)
        if id_to_filename.get(image_id) != clean_filename:
            stats["mapping_mismatches"] += 1

    for annotation in annotations:
        stats["coco_annotations"] += 1
        image_id = int(annotation["image_id"])
        filename = id_to_filename.get(image_id)
        if filename is None:
            stats["annotations_without_image"] += 1
            continue

        width, height = dimensions[filename]
        line, clipped = coco_bbox_to_yolo(annotation.get("bbox", []), width, height)
        if line is None:
            stats["invalid_test_boxes"] += 1
            continue
        labels[filename].append(line)
        stats["valid_test_boxes"] += 1
        if clipped:
            stats["clipped_test_boxes"] += 1

    return dict(labels), dimensions, stats


def mask_to_yolo(
    mask_data: bytes, min_instance_pixels: int
) -> tuple[list[str], tuple[int, int], int]:
    """Convert nonzero grayscale instance IDs to YOLO bounding boxes."""
    try:
        with Image.open(BytesIO(mask_data)) as mask_image:
            mask = np.asarray(mask_image.convert("L"))
    except (UnidentifiedImageError, OSError) as error:
        raise RuntimeError(f"Cannot read mask image: {error}") from error

    height, width = mask.shape
    valid = mask > 0
    if not np.any(valid):
        return [], (width, height), 0

    y_coordinates, x_coordinates = np.nonzero(valid)
    instance_ids = mask[valid].astype(np.int64)
    largest_id = int(instance_ids.max())

    min_x = np.full(largest_id + 1, width, dtype=np.int32)
    min_y = np.full(largest_id + 1, height, dtype=np.int32)
    max_x = np.full(largest_id + 1, -1, dtype=np.int32)
    max_y = np.full(largest_id + 1, -1, dtype=np.int32)
    pixel_counts = np.bincount(instance_ids, minlength=largest_id + 1)

    np.minimum.at(min_x, instance_ids, x_coordinates)
    np.minimum.at(min_y, instance_ids, y_coordinates)
    np.maximum.at(max_x, instance_ids, x_coordinates)
    np.maximum.at(max_y, instance_ids, y_coordinates)

    lines: list[str] = []
    skipped_small = 0
    for instance_id in np.unique(instance_ids):
        if pixel_counts[instance_id] < min_instance_pixels:
            skipped_small += 1
            continue

        x1 = int(min_x[instance_id])
        y1 = int(min_y[instance_id])
        x2 = int(max_x[instance_id]) + 1
        y2 = int(max_y[instance_id]) + 1
        if x2 <= x1 or y2 <= y1:
            skipped_small += 1
            continue

        center_x = ((x1 + x2) / 2.0) / width
        center_y = ((y1 + y2) / 2.0) / height
        box_width = (x2 - x1) / width
        box_height = (y2 - y1) / height
        lines.append(
            f"{APPLE_CLASS_ID} {center_x:.8f} {center_y:.8f} "
            f"{box_width:.8f} {box_height:.8f}"
        )

    return lines, (width, height), skipped_small


def atomic_write_bytes(path: Path, data: bytes, overwrite: bool) -> None:
    if path.exists() and not overwrite:
        raise FileExistsError(f"Output file already exists: {path}")
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_name(path.name + ".part")
    temporary.write_bytes(data)
    temporary.replace(path)


def atomic_write_text(path: Path, text: str, overwrite: bool) -> None:
    atomic_write_bytes(path, text.encode("utf-8"), overwrite)


def validate_image(data: bytes) -> tuple[int, int]:
    try:
        with Image.open(BytesIO(data)) as image:
            return image.size
    except (UnidentifiedImageError, OSError) as error:
        raise RuntimeError(f"Cannot read image: {error}") from error


def output_image_name(split: str, source_name: str) -> str:
    return f"minneapple_{split}_{PurePosixPath(source_name).name}"


def output_label_name(split: str, source_name: str) -> str:
    image_name = output_image_name(split, source_name)
    return str(Path(image_name).with_suffix(".txt"))


def prepare_output_directories(output: Path) -> None:
    for split in ("train", "test"):
        (output / split / "images").mkdir(parents=True, exist_ok=True)
        (output / split / "labels").mkdir(parents=True, exist_ok=True)


def run(args: argparse.Namespace) -> dict[str, Any]:
    if not args.train_archive.is_file():
        raise FileNotFoundError(f"Train archive not found: {args.train_archive}")
    if not args.test_archive.is_file():
        raise FileNotFoundError(f"Test archive not found: {args.test_archive}")
    if args.min_instance_pixels < 1:
        raise ValueError("--min-instance-pixels must be at least 1")

    test_labels, test_dimensions, test_stats = load_test_labels(args.test_archive)

    stats: dict[str, Any] = {
        "mode": "execute" if args.execute else "dry-run",
        "class_id": APPLE_CLASS_ID,
        "class_name": "apple",
        "train_archive": str(args.train_archive.resolve()),
        "test_archive": str(args.test_archive.resolve()),
        "output": str(args.output.resolve()),
        "train_images": 0,
        "train_masks": 0,
        "train_pairs": 0,
        "train_boxes": 0,
        "train_empty_masks": 0,
        "skipped_small_instances": 0,
        "test_images": 0,
        "test_boxes": 0,
        "corrupt_images": 0,
        "corrupt_masks": 0,
        "dimension_mismatches": [],
        "missing_train_masks": [],
        "missing_train_images": [],
        "test_images_without_coco_entry": [],
        "coco_entries_without_test_image": [],
        **test_stats,
    }

    train_image_dimensions: dict[str, tuple[int, int]] = {}
    train_mask_dimensions: dict[str, tuple[int, int]] = {}
    train_image_names: set[str] = set()
    train_mask_names: set[str] = set()
    copied_test_names: set[str] = set()

    if args.execute:
        prepare_output_directories(args.output)

    # Streaming mode scans the compressed archive only once and avoids a full
    # extraction or repeated random seeks through a 1.8 GB gzip file.
    with tarfile.open(args.train_archive, mode="r|gz") as archive:
        for member in archive:
            if not member.isfile():
                continue
            name = member.name
            suffix = PurePosixPath(name).suffix.lower()
            if suffix not in IMAGE_SUFFIXES:
                continue
            if not (
                name.startswith(TRAIN_IMAGE_PREFIX)
                or name.startswith(TRAIN_MASK_PREFIX)
                or name.startswith(TEST_IMAGE_PREFIX)
            ):
                continue

            source = archive.extractfile(member)
            if source is None:
                continue
            data = source.read()
            basename = PurePosixPath(name).name

            if name.startswith(TRAIN_IMAGE_PREFIX):
                stats["train_images"] += 1
                train_image_names.add(basename)
                try:
                    dimensions = validate_image(data)
                except RuntimeError:
                    stats["corrupt_images"] += 1
                    continue
                train_image_dimensions[basename] = dimensions
                if args.execute:
                    destination = (
                        args.output
                        / "train"
                        / "images"
                        / output_image_name("train", basename)
                    )
                    atomic_write_bytes(destination, data, args.overwrite)

            elif name.startswith(TRAIN_MASK_PREFIX):
                stats["train_masks"] += 1
                train_mask_names.add(basename)
                try:
                    lines, dimensions, skipped_small = mask_to_yolo(
                        data, args.min_instance_pixels
                    )
                except RuntimeError:
                    stats["corrupt_masks"] += 1
                    continue
                train_mask_dimensions[basename] = dimensions
                stats["train_boxes"] += len(lines)
                stats["skipped_small_instances"] += skipped_small
                if not lines:
                    stats["train_empty_masks"] += 1
                if args.execute:
                    destination = (
                        args.output
                        / "train"
                        / "labels"
                        / output_label_name("train", basename)
                    )
                    text = "\n".join(lines)
                    if text:
                        text += "\n"
                    atomic_write_text(destination, text, args.overwrite)

            elif name.startswith(TEST_IMAGE_PREFIX):
                stats["test_images"] += 1
                copied_test_names.add(basename)
                try:
                    actual_dimensions = validate_image(data)
                except RuntimeError:
                    stats["corrupt_images"] += 1
                    continue

                expected_dimensions = test_dimensions.get(basename)
                if expected_dimensions is None:
                    stats["test_images_without_coco_entry"].append(basename)
                elif expected_dimensions != actual_dimensions:
                    stats["dimension_mismatches"].append(
                        {
                            "file": basename,
                            "image": list(actual_dimensions),
                            "annotation": list(expected_dimensions),
                        }
                    )

                lines = test_labels.get(basename, [])
                stats["test_boxes"] += len(lines)
                if args.execute:
                    image_destination = (
                        args.output
                        / "test"
                        / "images"
                        / output_image_name("test", basename)
                    )
                    label_destination = (
                        args.output
                        / "test"
                        / "labels"
                        / output_label_name("test", basename)
                    )
                    atomic_write_bytes(image_destination, data, args.overwrite)
                    text = "\n".join(lines)
                    if text:
                        text += "\n"
                    atomic_write_text(label_destination, text, args.overwrite)

    common_train_names = train_image_names & train_mask_names
    stats["train_pairs"] = len(common_train_names)
    stats["missing_train_masks"] = sorted(train_image_names - train_mask_names)
    stats["missing_train_images"] = sorted(train_mask_names - train_image_names)

    for basename in sorted(common_train_names):
        image_size = train_image_dimensions.get(basename)
        mask_size = train_mask_dimensions.get(basename)
        if image_size is not None and mask_size is not None and image_size != mask_size:
            stats["dimension_mismatches"].append(
                {
                    "file": basename,
                    "image": list(image_size),
                    "mask": list(mask_size),
                }
            )

    stats["coco_entries_without_test_image"] = sorted(
        set(test_labels) - copied_test_names
    )

    if args.execute:
        manifest = {
            "source": "MinneApple",
            "target_task": "YOLO object detection",
            "target_class": {"id": APPLE_CLASS_ID, "name": "apple"},
            "split_policy": {
                "train": "Official train images converted from instance masks",
                "test": "Official detection test images and COCO bounding boxes",
                "validation": "Not created here; must later be grouped by capture session",
            },
            "license": {
                "name": "CC BY-NC-SA 3.0 US",
                "url": "https://creativecommons.org/licenses/by-nc-sa/3.0/us/",
                "note": (
                    "Allowed for the current academic/internship prototype; "
                    "reassess redistribution and any future commercial use."
                ),
            },
        }
        atomic_write_text(
            args.output / "source_manifest.json",
            json.dumps(manifest, indent=2, ensure_ascii=False) + "\n",
            args.overwrite,
        )
        atomic_write_text(
            args.output / "conversion_report.json",
            json.dumps(stats, indent=2, ensure_ascii=False) + "\n",
            args.overwrite,
        )

    return stats


def main() -> int:
    args = parse_args()
    try:
        stats = run(args)
    except (FileNotFoundError, FileExistsError, RuntimeError, ValueError, zipfile.BadZipFile, tarfile.TarError) as error:
        print(f"ERROR: {error}", file=sys.stderr)
        return 1

    print(json.dumps(stats, indent=2, ensure_ascii=False))
    if not args.execute:
        print(
            "\nDry-run completed. No files were written. "
            "Run again with --execute after reviewing this report."
        )
    else:
        print(f"\nConversion completed: {args.output.resolve()}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
